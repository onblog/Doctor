#!/usr/bin/env node
/**
 * Splits the generated seed SQL into per-day batches that respect the D1 free tier
 * write budget (100,000 rows written per day).
 *
 * Why not just split by file size: `wrangler d1 execute` bills per *row written*, so
 * the useful unit is statements, not bytes. The current dataset needs ~173k writes,
 * which is ~1.7 days of quota. Cutting it in half gives two safe batches.
 *
 * Statements are parsed with a quote-aware scanner: long free-text columns contain
 * literal newlines, so "one line = one statement" is not true for this dump.
 *
 * Usage:
 *   node scripts/split-days.mjs            # 2 days, balanced
 *   node scripts/split-days.mjs --days 3   # explicit day count
 *   node scripts/split-days.mjs --rows 90000
 *
 * Output:
 *   build/day-1/seed-0001.sql ...
 *   build/day-2/seed-0001.sql ...
 *   build/days.json
 */

import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const BUILD_DIR = "build";
const CHUNK_BYTES = 1_800_000;

const args = process.argv.slice(2);
const flag = (name) => {
  const index = args.indexOf(name);
  return index >= 0 ? args[index + 1] : null;
};

function listSeedFiles() {
  if (!existsSync(BUILD_DIR)) return [];
  return readdirSync(BUILD_DIR)
    .filter((name) => /^seed-\d+\.sql$/.test(name))
    .sort()
    .map((name) => join(BUILD_DIR, name));
}

/** Splits a SQL script on top-level semicolons, ignoring those inside string literals. */
function splitStatements(text) {
  const statements = [];
  let start = 0;
  let inString = false;

  for (let i = 0; i < text.length; i += 1) {
    const char = text[i];

    if (inString) {
      if (char === "'") {
        if (text[i + 1] === "'") {
          i += 1; // escaped quote, stays inside the literal
        } else {
          inString = false;
        }
      }
      continue;
    }

    if (char === "'") {
      inString = true;
      continue;
    }

    if (char === ";") {
      const statement = text.slice(start, i + 1).trim();
      if (statement) statements.push(statement);
      start = i + 1;
    }
  }

  const tail = text.slice(start).trim();
  if (tail) statements.push(tail);
  return statements;
}

const TABLE_OF = /^INSERT\s+(?:OR\s+REPLACE\s+|OR\s+IGNORE\s+)?INTO\s+`?([A-Za-z0-9_]+)`?/i;

function tableOf(statement) {
  const match = TABLE_OF.exec(statement);
  return match ? match[1] : "unknown";
}

function main() {
  const files = listSeedFiles();
  if (!files.length) {
    console.error(`没有找到 ${BUILD_DIR}/seed-*.sql，先运行 npm run data:convert`);
    process.exit(1);
  }

  // 1. Read every statement once and remember which table it belongs to.
  const statements = [];
  let skipped = 0;
  for (const file of files) {
    // Each chunk file starts with "-- generated by ..." comment lines; strip them before
    // parsing, otherwise the first INSERT of every file is glued to the comment and
    // would be mistaken for non-SQL.
    const text = readFileSync(file, "utf8").replace(/^(?:--[^\n]*\n)+/, "");
    for (const statement of splitStatements(text)) {
      if (!/^INSERT/i.test(statement)) {
        skipped += 1;
        continue;
      }
      statements.push({ sql: statement, table: tableOf(statement) });
    }
  }
  if (skipped > 0) console.warn(`注意：跳过了 ${skipped} 段非 INSERT 片段（应为 0）。`);

  const totalRows = statements.length;
  const days = Math.max(1, Number.parseInt(flag("--days") ?? "2", 10));
  const maxRowsPerDay = Number.parseInt(flag("--rows") ?? "0", 10);
  const targetPerDay = maxRowsPerDay > 0 ? maxRowsPerDay : Math.ceil(totalRows / days);

  // 2. Fill day by day, keeping the original table order (dictionary first, indexes last).
  const buckets = [];
  let current = { rows: 0, statements: [] };
  for (const item of statements) {
    if (current.rows >= targetPerDay && buckets.length < days - 1) {
      buckets.push(current);
      current = { rows: 0, statements: [] };
    }
    current.statements.push(item);
    current.rows += 1;
  }
  if (current.statements.length) buckets.push(current);

  // 3. Write each day out, still chunked by bytes so one request stays small.
  const manifest = { totalRows, targetPerDay, days: [] };

  for (let index = 0; index < buckets.length; index += 1) {
    const day = index + 1;
    const dir = join(BUILD_DIR, `day-${day}`);
    rmSync(dir, { recursive: true, force: true });
    mkdirSync(dir, { recursive: true });

    let chunk = [];
    let chunkBytes = 0;
    const files = [];
    const tables = {};

    const flush = () => {
      if (!chunk.length) return;
      const name = `seed-${String(files.length + 1).padStart(4, "0")}.sql`;
      writeFileSync(
        join(dir, name),
        `-- day ${day} · chunk ${files.length + 1}\n-- generated by scripts/split-days.mjs\n${chunk.join("\n")}\n`
      );
      files.push({ name, statements: chunk.length, bytes: chunkBytes });
      chunk = [];
      chunkBytes = 0;
    };

    for (const item of buckets[index].statements) {
      chunk.push(item.sql);
      chunkBytes += Buffer.byteLength(item.sql, "utf8") + 1;
      tables[item.table] = (tables[item.table] ?? 0) + 1;
      if (chunkBytes >= CHUNK_BYTES) flush();
    }
    flush();

    manifest.days.push({ day, rows: buckets[index].rows, files, tables });
  }

  writeFileSync(join(BUILD_DIR, "days.json"), `${JSON.stringify(manifest, null, 2)}\n`);

  console.log(`总计 ${totalRows} 条写入语句，按每天 ≤ ${targetPerDay} 行切成 ${buckets.length} 天：`);
  for (const day of manifest.days) {
    const perTable = Object.entries(day.tables)
      .map(([table, count]) => `${table}:${count}`)
      .join("  ");
    console.log(
      `  第 ${day.day} 天  ${String(day.rows).padStart(6)} 行  ${day.files.length} 个文件  → ${BUILD_DIR}/day-${day.day}/`
    );
    console.log(`           ${perTable}`);
  }
  console.log(`清单：${BUILD_DIR}/days.json`);
  console.log(`导入：npm run data:load -- --remote --day 1   （第二天再跑 --day 2）`);
}

main();
